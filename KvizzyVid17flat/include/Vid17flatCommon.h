// ****************************************************************************
// *        Получить значение напряжения источника питания схемы (Вольт)      *
// ****************************************************************************
float getVbattf()
{
  uint32_t Vbatt = 0;
  // Выполняем 16 считываний показаний напряжения питания (со среднего вывода делителя
  // напряжения (2 х 1MOм) и усредняем значения)  
  for(int i = 0; i < 16; i++) 
  {
    Vbatt = Vbatt + analogReadMilliVolts(A0); // ADC with correction   
  }
  // Пересчитываем значения в вольты
  float Vbattf = 2 * Vbatt / 16 / 1000.0;     // attenuation ratio 1/2, mV --> V
  return Vbattf;
}

