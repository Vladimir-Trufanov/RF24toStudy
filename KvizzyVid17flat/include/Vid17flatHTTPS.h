// 2025-09-04 json-сообщения передаются через параметры запросов и записываются 
//            в базу данных в полном виде (с фигурными скобками в начале и в 
//            завершении json-сообщения)
// -------------------------------------------------------------------------------------------------------------------
// http://localhost:100/State/?cycle=21&num=5&ctrl=204&sjson={"trkpt":{"lat":61856308,"lon":33396584,"color":"white"}}
// https://kwinflat.ru/State/?cycle=7&num=5&ctrl=203&sjson={"trkpt":{"lat":52518611,"lon":13376111,"color":"yellow"}}
// http://localhost:100/State/?cycle=114&num=6&ctrl=207&sjson={"dht22":{"humi":87,"tempC":264}}   
// -------------------------------------------------------------------------------------------------------------------

// Ответы State на ошибки:

// '{"exit":200}'  - не разобран номер цикла контроллера 'cycle'
// '{"exit":201}'  - не разобран тип сообщения 'num'
// '{"exit":202}'  - не разобран номер контроллера 'ctrl'
// '{"exit":203}'  - не выделено json-сообщение на приёме 'sjson'

// '{"exit":216}'  - если все параметры отсутствуют, то считаем что вошли на 
//                   State в режиме просмотра последних обращений контроллеров

// Реестр образцов(типов) json-сообщений на State (по параметру num в запросе):
// 3  -> s_DHT11,    '{"dht11":{"humi":46,"tempC":248}}'                           // влажность = 46%, температура = 24.8°C  
// 4  -> s_GPXwpt,   '{"wpt":{"lat":52518611,"lon":13376111}}'                     // координаты путевой точки: широта 52.518611, долгота 13.376111
// 5  -> s_GPXtrkpt, '{"trkpt":{"lat":61856308,"lon":33396584,"color":"white"}}'   // точка трека: широта 61.856308, долгота 33.396584, цвет белый
// 6  -> s_DHT22,    '{"dht22":{"humi":87,"tempC":264}}'                           // влажность = 87%, температура = 26.4°C  
// 7  -> s_Water,    '{"water":{"level":697}}                                      // уровень воды = 697 единиц (0-1023)                                          
// 8  -> s_POWER     '{"vcc":{"power":491}}                                        // напряжение батареи 4.91В     

// Примеры запросов к State от контроллеров и ответов State:

// num=5 - точка трека от Sim900 в автомобиле (виртуального контроллера)
// ---------------------------------------------------------------------
// http://localhost:100/State/?cycle=21&num=5&ctrl=204&sjson={"trkpt":{"lat":61856308,"lon":33396584,"color":"white"}}
// <State>{"cycle":21}{"num":5}{"ctrl":204}{"sjson":{"trkpt":{"lat":61856308,"lon":33396584,"color":"white"}}}</State>

// num=6 - влажность и температура с датчика DHT22 в подвале
// ---------------------------------------------------------------------
// http://localhost:100/State/?cycle=114&num=6&ctrl=207&sjson={"dht22":{"humi":87,"tempC":264}}   <-запрос
// <State>{"cycle":114}{"num":6}{"ctrl":207}{"sjson":{dht22":{"humi":87,"tempC":264}}}</State>    <-ответ

// num=7 - уровень воды в подвале
// ---------------------------------------------------------------------
// http://localhost:100/State/?cycle=17&num=7&ctrl=207&sjson={"water":{"level":697}}              <-запрос
// <State>{"cycle":17}{"num":7}{"ctrl":207}{"sjson":{"water":{"level":697}}}</State>              <-ответ

// num=8 - напряжение питания контроллера и датчиков в подвале
// ---------------------------------------------------------------------
// http://localhost:100/State/?cycle=19&num=8&ctrl=207&sjson={"vcc":{"power":491}}                <-запрос
// <State>{"cycle":19}{"num":8}{"ctrl":207}{"sjson":{"vcc":{"power":491}}}</State>                <-ответ

// num=8 - напряжение питания контроллера в квартире (для приёма даанных из подвала)
// ---------------------------------------------------------------------
// http://localhost:100/State/?cycle=1953&num=8&ctrl=206&sjson={"vcc":{"power":337}}              <-запрос
// <State>{"cycle":1953}{"num":8}{"ctrl":206}{"sjson":{"vcc":{"power":337}}}</State>              <-ответ

// --------------------------------------------------------------------- 

