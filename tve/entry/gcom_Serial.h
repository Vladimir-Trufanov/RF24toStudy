#ifndef GCOMSERIAL
#define GCOMSERIAL1
#pragma once  

#include "mcom_nrf24l01.h"  // выполнение команд модулем nRF24L01+

int gcSerial();

int ccom='x';  // полученная команда из последовательного порта
int ncom=-1;   // номер команды

int gcSerial()
{
  // Выполняем первую проверку: 
  // если поступила команда из последовательного порта, то отрабатываем её
  if (Serial.available())
  {
    ccom = Serial.read();
    // Serial.print("получили = "); Serial.println(ccom); 
    
    // Выполняем команду по завершению заданного контрольного действия 
    if (ccom == '0') ncom=-1;
    // Выполняем команду проверки работоспособности модуля nRF24L01+ 
    // и правильность его подключения   
    else if (ccom == '1') 
    {
      Check_nRF24L01();
      ncom=-1;
    }
    // ---Выполняем команду по трассировке утечек памяти
    // (показывать оставшуюся свободную память)
    // или отменяем её
    else if (ccom == '2') 
    {
      Serial.println("\nКоманда 1:"); 
      ncom=2;
    }
  }

  //Serial.print("ccom = "); Serial.println(ccom); 

  // Выполняем вторую проверку: 
  // если следует продолжать действие из нескольких циклов, то делаем это
  if (ncom>0)
  {
    if (ncom==2) 
    {
      Serial.println("121"); 
      delay(1000);
    }
  }
  //Serial.print("ncom = "); Serial.println(ncom); 
  return ncom;
} 
#endif 

